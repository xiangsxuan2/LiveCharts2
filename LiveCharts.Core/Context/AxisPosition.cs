namespace LiveChartsCore.Context
{
    /// <summary>
    /// 坐标轴位置枚举
    /// 定义坐标轴位于图表的哪一侧
    /// </summary>
    public enum AxisPosition
    {
        /// <summary>
        /// 左侧或底部位置
        /// 对于Y轴：左侧
        /// 对于X轴：底部
        /// </summary>
        LeftOrBottom,

        /// <summary>
        /// 右侧或顶部位置
        /// 对于Y轴：右侧
        /// 对于X轴：顶部
        /// </summary>
        RightOrTop
    }
}