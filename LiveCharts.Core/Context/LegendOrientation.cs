namespace LiveChartsCore.Context
{
    /// <summary>
    /// 图例方向枚举
    /// 定义图例的排列方向
    /// </summary>
    public enum LegendOrientation
    {
        /// <summary>
        /// 自动方向，根据图例位置自动选择
        /// </summary>
        Auto,

        /// <summary>
        /// 水平方向，图例项水平排列
        /// </summary>
        Horizontal,

        /// <summary>
        /// 垂直方向，图例项垂直排列
        /// </summary>
        Vertical
    }
}