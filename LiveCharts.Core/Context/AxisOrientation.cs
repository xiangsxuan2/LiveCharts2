namespace LiveChartsCore.Context
{
    /// <summary>
    /// 坐标轴方向枚举
    /// 定义坐标轴是水平方向（X轴）还是垂直方向（Y轴）
    /// </summary>
    public enum AxisOrientation
    {
        /// <summary>
        /// 未知方向，通常表示未初始化
        /// </summary>
        Unknown,

        /// <summary>
        /// 水平方向，X轴
        /// </summary>
        X,

        /// <summary>
        /// 垂直方向，Y轴
        /// </summary>
        Y
    }
}